def get_ledgar_label(idx: int) -> str:
    """Return LEDGAR label name for given index (0-99)."""
    if 0 <= idx < len(LEDGAR_LABELS):
        return LEDGAR_LABELS[idx]
    return f"LABEL_{idx}"


def get_ledgar_labels() -> list[str]:
    """Return list of all 100 LEDGAR label names."""
    return list(LEDGAR_LABELS)
